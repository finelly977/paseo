import esbuild from "esbuild";
import fs from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "../../..");
const repoRoot = path.resolve(appRoot, "../..");
const require = createRequire(import.meta.url);

const pdfEntry = require.resolve("pdfjs-dist/build/pdf.mjs");
const pdfWorkerEntry = require.resolve("pdfjs-dist/build/pdf.worker.min.mjs");

// Metro 的 Babel 解析器不支持非字面量动态 import(this.workerSrc)，会在 expo export 阶段直接报错。
// 运行时 Worker 通过离线 Blob URL（GlobalWorkerOptions.workerSrc）启动；若环境不支持 Worker 且未注入
// globalThis.pdfjsWorker，则在伪 Worker 分支显式抛错，避免保留动态 import() 语法节点。
const fakeWorkerDynamicImportPattern =
  /const\s+worker\s*=\s*await\s+import\(\s*\/\*webpackIgnore:\s*true\*\/\s*this\.workerSrc\s*\)\s*;\s*return\s+worker\.WorkerMessageHandler\s*;/;

const stripDynamicWorkerImportPlugin = {
  name: "strip-pdfjs-dynamic-worker-import",
  setup(build) {
    build.onLoad({ filter: /[/\\]pdfjs-dist[/\\]build[/\\]pdf\.mjs$/ }, async (args) => {
      const source = await fs.readFile(args.path, "utf8");
      if (!fakeWorkerDynamicImportPattern.test(source)) {
        throw new Error(
          `未能匹配 pdf.mjs 中的伪 Worker 动态 import 语句，请检查 pdfjs-dist 版本：${args.path}`,
        );
      }
      const patched = source.replace(
        fakeWorkerDynamicImportPattern,
        'throw new Error("PDF Web Worker 启动失败，且当前环境不支持动态导入 Worker 脚本。");',
      );
      return { contents: patched, loader: "js" };
    });
  },
};

const pdfBundleResult = await esbuild.build({
  entryPoints: [pdfEntry],
  plugins: [stripDynamicWorkerImportPlugin],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  target: ["ios15", "chrome100"],
  minify: true,
  define: {
    "import.meta.url": '""',
  },
  logLevel: "info",
});

const pdfBundleCode = pdfBundleResult.outputFiles[0]?.text;
if (!pdfBundleCode) {
  throw new Error("Failed to bundle pdfjs-dist");
}

const rawWorkerCode = await fs.readFile(pdfWorkerEntry, "utf8");
const workerBundleResult = await esbuild.transform(rawWorkerCode, {
  loader: "js",
  target: ["ios15", "chrome100"],
  minify: true,
});
const pdfWorkerCode = workerBundleResult.code;

const pdfJsOut = path.join(__dirname, "pdfjs-bundle.gen.js");
const pdfJsDtsOut = path.join(__dirname, "pdfjs-bundle.gen.d.ts");
const pdfWorkerOut = path.join(__dirname, "pdf-worker.gen.ts");

await fs.writeFile(
  pdfJsOut,
  `/* oxlint-disable */\n// Generated by packages/app/src/file-pane/document-preview/build-pdf-runtime.mjs.\n// Do not edit by hand.\n${pdfBundleCode}\n`,
);

await fs.writeFile(
  pdfJsDtsOut,
  `// Generated by packages/app/src/file-pane/document-preview/build-pdf-runtime.mjs.
// Do not edit by hand.

export interface PdfViewport {
  width: number;
  height: number;
  transform?: number[];
}

export interface PdfPageProxy {
  getViewport(params: { scale: number }): PdfViewport;
  render(params: {
    canvasContext: CanvasRenderingContext2D;
    viewport: PdfViewport;
    transform?: number[];
  }): { promise: Promise<void>; cancel(): void };
}

export interface PdfDocumentProxy {
  numPages: number;
  getPage(pageNumber: number): Promise<PdfPageProxy>;
  destroy(): Promise<void>;
}

export interface PdfLoadingTask {
  promise: Promise<PdfDocumentProxy>;
  destroy(): Promise<void>;
}

export declare const GlobalWorkerOptions: {
  workerSrc: string;
  workerPort: Worker | null;
};

export declare function getDocument(src: { data: Uint8Array }): PdfLoadingTask;
`,
);

await fs.writeFile(
  pdfWorkerOut,
  `// Generated by packages/app/src/file-pane/document-preview/build-pdf-runtime.mjs.\n// Do not edit by hand.\n\nexport const pdfWorkerCode = ${JSON.stringify(pdfWorkerCode)};\n`,
);

console.log(
  `Wrote ${path.relative(repoRoot, pdfJsOut)} (${pdfBundleCode.length} bytes) and ${path.relative(repoRoot, pdfWorkerOut)} (${pdfWorkerCode.length} bytes)`,
);
